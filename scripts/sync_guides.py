"""Generate repository routing guides from configs/tools.json; standard library only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def bullets(values):
    return "\n".join(f"- {value}" for value in values)


def generate():
    catalog = json.loads((ROOT / "configs/tools.json").read_text(encoding="utf-8"))
    tools = catalog["tools"]
    by_id = {tool["id"]: tool for tool in tools}
    if len(by_id) != len(tools):
        raise ValueError("Duplicate tool IDs")
    for tool in tools:
        folder = ROOT / "repos" / tool["folder"]
        if folder.is_symlink() or folder.resolve().parent != (ROOT / "repos").resolve():
            raise ValueError(f"Invalid repository folder: {folder}")
        folder.mkdir(parents=True, exist_ok=True)
        package_text = bullets([f"`{p}`" for p in tool["packages"]]) if tool["packages"] else "Không có package runtime riêng cần cài; đây là bộ hướng dẫn."
        upstream = ""
        if tool.get("upstreamGuide"):
            upstream = f"\nKhi sửa chính thư viện này, đọc [AGENTS upstream được lưu nguyên bản](../../{tool['upstreamGuide']}). Lệnh build/test ở đó chỉ áp dụng cho phát triển thư viện.\n"
        text = f"""# {tool['name']} — hướng dẫn trong Piu Editor

<!-- Generated by scripts/sync_guides.py from configs/tools.json. -->
Áp dụng [AGENTS gốc](../../AGENTS.md), [bản đồ](../../docs/REPO-MAP.md) và [workflow](../../docs/WORKFLOW.md). Chỉ dẫn này dùng cho tích hợp vào video; muốn sửa nội dung hãy cập nhật registry rồi chạy sync.

**Vai trò:** {tool['role']}

**Nguồn:** [{tool['upstream']}]({tool['upstream']})

**ID trong project.json:** `{tool['id']}`

## Khi nào dùng

{bullets(tool['useWhen'])}

## Khi không nên chọn

{bullets(tool['avoidWhen'])}

## Đọc đúng chỗ

{bullets([f'[{p}]({p})' for p in tool['readFirst']])}

Source tham khảo được tải riêng, không đi kèm Git repo chính. Nếu chưa có các file trên, chạy từ gốc:

```powershell
python scripts/bootstrap_repos.py --tool {tool['id']}
```

Chỉ mở phần tài liệu khớp nhiệm vụ. Commit được khóa trong [manifest](../../repo-manifest.json); bản source local có thể khác package phát hành sẽ cài trong project. Lệnh tải giữ nguyên source đã có; kiểm tra file bằng `python scripts/studio.py validate --sources` sau khi đã tải đủ bộ.

## Package hoặc binary liên quan

{package_text}

Đây là danh sách để lựa chọn, không phải lệnh cài tất cả. Nếu cần cài, dùng phiên bản tương thích, lockfile và môi trường của `projects/<id>/`; không mặc định install ở thư mục repo tham khảo này.

## Cách đưa vào video

{bullets(tool['integration'])}

## Điểm phải kiểm tra

{bullets(tool['pitfalls'])}

Đọc LICENSE/COPYING của bản dùng thật, kiểm tra asset đầu vào, thử preview ngắn và kiểm tra file xuất theo brief. Không tuyên bố hoạt động chỉ vì API có trong source.

## Bàn giao cho bước tiếp theo

Ghi công cụ/phiên bản và quyết định vào project; giữ bản gốc, lưu dẫn xuất ở working/previews hoặc output đúng vai trò. Khi sửa guide hoặc registry, chạy `python scripts/studio.py validate` từ gốc workspace.

Liên quan: {', '.join(f"[{by_id[x]['name']}](../{by_id[x]['folder']}/AGENTS.md)" for x in tool['related'])}.
{upstream}"""
        (folder / "AGENTS.md").write_text(text, encoding="utf-8")

    table = "\n".join(
        f"| [{t['name']}](../repos/{t['folder']}/AGENTS.md) | {t['role']} | {t['useWhen'][0]} |"
        for t in tools
    )
    map_text = f"""# Bản đồ công cụ của Piu Editor

<!-- Generated by scripts/sync_guides.py from configs/tools.json. -->
Đọc [AGENTS gốc](../AGENTS.md) trước, thực hiện [WORKFLOW](WORKFLOW.md). Chọn ít công cụ nhất đủ tạo ra kết quả đúng yêu cầu. Nguyên liệu người dùng nằm trong `Source/`, source thư viện tham khảo nằm trong `repos/`, code dựng video nằm trong `projects/`.

Repo chính chỉ chứa hướng dẫn của 18 công cụ. Tải toàn bộ source bằng `python scripts/bootstrap_repos.py`, hoặc tải riêng bằng `--tool <id>`. Phiên bản được khóa trong manifest; xem [cách clone và quản lý Git](GIT.md).

## Bắt đầu bằng loại công việc

| Người dùng muốn | Lựa chọn đầu tiên | Thêm khi thực sự cần |
|---|---|---|
| Cắt video gốc, bỏ đoạn chờ, crop dọc, nối clip, thêm nhạc | FFmpeg / ffprobe | Remotion nếu layout/animation phức tạp |
| Ghép ảnh thành video có chữ, phụ đề, đồ hoạ chuyển động | Remotion + Remotion Skills | GSAP, SVGO, Satori, dotLottie theo asset |
| Bài giảng vector có nhiều hình biến đổi | Motion Canvas hoặc Remotion | FFmpeg để hoàn tất; chọn một timeline chính |
| Quay sản phẩm/scene 3D | Three.js + Fiber + remotion/three trong Remotion | Drei; Rapier cho vật lý; Postprocessing cho hiệu ứng |
| Giao diện web nghe thử hoặc tương tác | Motion, Howler khi app cần | Không để clock UI điều khiển bản xuất |
| Media IO/conversion bằng API JS | Mediabunny | Gói server khi cần; FFmpeg nếu CLI thuận tiện hơn |

Chỉ gọi công cụ tạo ảnh/giọng/nhạc bên ngoài khi nội dung và yêu cầu cần đến; 18 repo không tự cung cấp đủ tài nguyên sáng tác đó.

## Danh mục {len(tools)} repo

| Repo và hướng dẫn riêng | Nhiệm vụ | Khi dùng |
|---|---|---|
{table}

Registry đọc bằng máy: [configs/tools.json](../configs/tools.json). Để đổi bảng hoặc guide con, sửa registry và `scripts/sync_guides.py`, rồi chạy sync. Thêm repo theo [EXTENDING](EXTENDING.md).

## Các đường phối hợp thường gặp

- **Footage → FFmpeg → output:** đường ngắn cho cắt ghép. Giữ lệnh tái tạo và QA, không cần framework React.
- **Ảnh/chữ/audio → Remotion → output:** composition nhiều cảnh. GSAP qua `@remotion/gsap` khi timeline DOM/SVG phức tạp; chưa cần 3D thì không cài Three.
- **Layout → Satori → SVG → SVGO nếu phù hợp → Remotion:** pipeline card tĩnh. Giữ ID/lớp cần animate và kiểm tra font.
- **Lottie asset → dotLottie setFrame → composition:** load WASM/asset trước khi capture, ánh xạ FPS rõ ràng.
- **Model → Three/Fiber/Drei → @remotion/three → Remotion:** pose theo frame. Rapier tạo dữ liệu pose bake trước; Postprocessing chạy cùng renderer được chọn.
- **Motion Canvas → clip/image sequence → Remotion hoặc FFmpeg:** phối hợp ở ranh giới file, không trộn hai cây JSX và hai clock.
- **Howler cho nghe thử → cùng file audio trên timeline Remotion/FFmpeg:** bản MP4 không lấy âm thanh chỉ từ playback UI.

## Không được suy luận nhầm

- Có repo source không có nghĩa dependency/binary đã cài hoặc API đã được thử trên máy này.
- GSAP, Anime.js và Motion là các lựa chọn chồng chức năng; không cài cả ba theo quán tính.
- SVGO tối ưu SVG; Satori kết xuất layout; dotLottie phát asset. Chúng không thay thế hoạ sĩ sinh mọi nội dung từ prompt.
- Seed/timestep cố định không tự giải quyết seek vật lý; cần bake hoặc reset/snapshot/replay.
- Tài liệu upstream có lệnh phát triển thư viện; công việc dựng video dùng app của project riêng.

## Ví dụ một yêu cầu

“Dùng ảnh Source/images và nhạc Source/music làm video dọc 30 giây, chữ tiếng Việt”: kiểm tra ảnh/nhạc → tạo project → brief và shot list → chọn Remotion → viết composition frame-based → kiểm tra font, crop, chữ, tiếng → xuất và ffprobe. Không cần cài Rapier, Motion Canvas hoặc Howler nếu không xuất hiện nhu cầu tương ứng.
"""
    (ROOT / "docs/REPO-MAP.md").write_text(map_text, encoding="utf-8")
    print(f"Updated {len(tools)} repository guides and docs/REPO-MAP.md")


if __name__ == "__main__":
    generate()
